namespace OMGF\Tests\Integration\Admin;

use OMGF\Admin\Actions;
use OMGF\Admin\Settings;
use OMGF\Helper as OMGF;
use OMGF\Tests\TestCase;

class ActionsTest extends TestCase {
	/**
	 * @see Actions::init_admin()
	 * @return void
	 */
	public function testInitAdmin() {
		new Actions();

		do_action( '_admin_menu' );

		$this->assertTrue( class_exists( '\OMGF\Admin\Settings' ) );
	}

	/**
	 * @see Actions::do_optimize()
	 * @return void
	 */
	public function testDoOptimize() {
		new Actions();

		$this->assertTrue( class_exists( '\OMGF\Admin\Optimize' ) );
	}

	/**
	 * @see Actions::update_settings()
	 * @return void
	 */
	public function testUpdateSettings() {
		$_POST[ '_wpnonce' ] = wp_create_nonce( 'omgf-optimize-settings-options' );
		$_POST[ 'action' ]   = 'omgf-update';

		$_POST[ 'omgf_test' ]       = 'test';
		$_POST[ 'omgf_test_array' ] = [ 'test' ];
		$_POST[ 'omgf_test_zero' ]  = 0;

		$class = new Actions();
		$class->update_settings();;

		$this->assertEquals( 'test', OMGF::get_option( 'omgf_test' ) );
		$this->assertEquals( [ 'test' ], OMGF::get_option( 'omgf_test_array' ) );
		$this->assertEquals( [], OMGF::get_option( 'omgf_test_zero' ) );
	}

	/**
	 * A malformed (scalar) value for an option that must be a nested array - e.g. when a proxy or
	 * security plugin flattens the array parameters - must be ignored, leaving the existing valid
	 * setting untouched instead of corrupting it.
	 *
	 * @see Actions::update_settings()
	 * @return void
	 */
	public function testUpdateSettingsIgnoresMalformedScalarForArrayOption() {
		$existing = [ 'handle-1' => [ 'open-sans' => [ 'normal' => 'on' ] ] ];

		OMGF::update_option( 'omgf_preload_fonts', $existing );

		$_POST                        = [];
		$_POST[ '_wpnonce' ]          = wp_create_nonce( 'omgf-optimize-settings-options' );
		$_POST[ 'action' ]            = 'omgf-update';
		$_POST[ 'omgf_preload_fonts' ] = 'on'; // Flattened array parameter.

		( new Actions() )->update_settings();

		$this->assertSame( $existing, OMGF::get_option( 'omgf_preload_fonts' ) );
	}

	/**
	 * Options generated by OMGF can't be updated using the settings form.
	 *
	 * @see Actions::update_settings()
	 * @return void
	 */
	public function testUpdateSettingsIgnoresReadOnlyOptions() {
		$existing = [ 'handle-1' => (object) [ 'id' => 'open-sans' ] ];

		OMGF::update_option( Settings::OMGF_OPTIMIZE_SETTING_OPTIMIZED_FONTS, $existing );
		OMGF::update_option( Settings::OMGF_OPTIMIZE_SETTING_OPTIMIZED_FONTS_FRONTEND, $existing );

		try {
			$_POST                                                           = [];
			$_POST[ '_wpnonce' ]                                             = wp_create_nonce( 'omgf-optimize-settings-options' );
			$_POST[ 'action' ]                                               = 'omgf-update';
			$_POST[ Settings::OMGF_OPTIMIZE_SETTING_OPTIMIZED_FONTS ]          = base64_encode( serialize( [ 'handle-2' => [] ] ) );
			$_POST[ Settings::OMGF_OPTIMIZE_SETTING_OPTIMIZED_FONTS_FRONTEND ] = serialize( [ 'handle-2' => [] ] );

			( new Actions() )->update_settings();

			$this->assertEquals( $existing, get_option( Settings::OMGF_OPTIMIZE_SETTING_OPTIMIZED_FONTS ) );
			$this->assertEquals( $existing, get_option( Settings::OMGF_OPTIMIZE_SETTING_OPTIMIZED_FONTS_FRONTEND ) );
		} finally {
			OMGF::delete_option( Settings::OMGF_OPTIMIZE_SETTING_OPTIMIZED_FONTS );
			OMGF::delete_option( Settings::OMGF_OPTIMIZE_SETTING_OPTIMIZED_FONTS_FRONTEND );
		}
	}

	/**
	 * A valid save must overwrite a previously corrupted (string) value instead of throwing a
	 * TypeError in array_replace(), so the option self-heals.
	 *
	 * @see Actions::update_settings()
	 * @return void
	 */
	public function testUpdateSettingsSelfHealsCorruptedArrayOption() {
		OMGF::update_option( 'omgf_unload_fonts', 'this-is-not-an-array' );

		$expected = [ 'handle-1' => [ 'open-sans' => [ 'normal' => 'on' ] ] ];

		$_POST                       = [];
		$_POST[ '_wpnonce' ]         = wp_create_nonce( 'omgf-optimize-settings-options' );
		$_POST[ 'action' ]           = 'omgf-update';
		$_POST[ 'omgf_unload_fonts' ] = $expected;

		( new Actions() )->update_settings();

		$this->assertSame( $expected, OMGF::get_option( 'omgf_unload_fonts' ) );
	}

	/**
	 * @see Actions::clean_stale_cache()
	 * @return void
	 */
	public function testCleanStaleCache() {
		new Actions();

		wp_mkdir_p( OMGF_UPLOAD_DIR . '/test_cache_key' );
		file_put_contents( OMGF_UPLOAD_DIR . '/test_cache_key/dummy.file', 'test' );

		add_filter( 'omgf_setting_cache_keys', [ $this, 'addTestCacheKey' ] );

		do_action( 'omgf_pre_update_setting_cache_keys', '', 'test_cache_key-mod-abc12' );

		remove_filter( 'omgf_setting_cache_keys', [ $this, 'addTestCacheKey' ] );

		$this->assertDirectoryDoesNotExist( OMGF_UPLOAD_DIR . '/test_cache_key' );
	}

	/**
	 * Only the old cache directory of the modified stylesheet is removed, not that of a stylesheet whose handle starts
	 * with the same characters, or of a new stylesheet whose handle looks like a modified cache key.
	 *
	 * @see Actions::clean_stale_cache()
	 * @return void
	 */
	public function testCleanStaleCacheKeepsOtherStylesheets() {
		new Actions();

		$dirs = [ 'handle-12', 'handle-1', 'theme' ];

		foreach ( $dirs as $dir ) {
			wp_mkdir_p( OMGF_UPLOAD_DIR . "/$dir" );
			file_put_contents( OMGF_UPLOAD_DIR . "/$dir/dummy.file", 'test' );
		}

		$cache_keys      = function () {
			return 'handle-12,handle-1,theme';
		};
		$optimized_fonts = function () {
			return array_fill_keys( [ 'handle-12', 'handle-1', 'theme', 'theme-mod-darkx' ], [] );
		};

		add_filter( 'omgf_setting_cache_keys', $cache_keys );
		add_filter( 'omgf_setting_optimized_fonts_frontend', $optimized_fonts );
		OMGF::reset_cache();

		try {
			do_action( 'omgf_pre_update_setting_cache_keys', '', 'handle-12,handle-1-mod-abc12,theme,theme-mod-darkx' );

			$this->assertDirectoryDoesNotExist( OMGF_UPLOAD_DIR . '/handle-1' );
			$this->assertDirectoryExists( OMGF_UPLOAD_DIR . '/handle-12' );
			$this->assertDirectoryExists( OMGF_UPLOAD_DIR . '/theme' );
		} finally {
			remove_filter( 'omgf_setting_cache_keys', $cache_keys );
			remove_filter( 'omgf_setting_optimized_fonts_frontend', $optimized_fonts );
			OMGF::reset_cache();

			foreach ( $dirs as $dir ) {
				OMGF::delete( OMGF_UPLOAD_DIR . "/$dir" );
			}
		}
	}

	/**
	 * Rotating and resetting a key remove only the previous key's directory, including handles containing -mod-.
	 *
	 * @see Actions::clean_stale_cache()
	 */
	public function testCleanStaleCacheRotatesAndResetsModifiedKeys() {
		$actions = new Actions();
		$cases = [
			[ 'theme-mod-old12', 'theme-mod-new34' ],
			[ 'theme-mod-old12', 'theme' ],
			[ 'theme-mod-dark-mod-old12', 'theme-mod-dark-mod-new34' ],
			[ 'theme-mod-dark-mod-old12', 'theme-mod-dark' ],
			[ 'theme-mod-old12', 'theme-mod-old12' ],
		];
		$fonts = function () {
			return [ 'theme' => [], 'theme-mod-dark' => [] ];
		};
		add_filter( 'omgf_setting_optimized_fonts_frontend', $fonts );

		try {
			foreach ( $cases as [ $old, $new ] ) {
				$keys = function () use ( $old ) {
					return "theme-12,$old";
				};
				foreach ( [ $old, 'theme-12' ] as $dir ) {
					wp_mkdir_p( OMGF_UPLOAD_DIR . "/$dir" );
					file_put_contents( OMGF_UPLOAD_DIR . "/$dir/test.css", 'cached' );
				}
				add_filter( 'omgf_setting_cache_keys', $keys );
				OMGF::reset_cache();

				try {
					$actions->clean_stale_cache( '', "theme-12,$new" );

					$this->assertSame( $old === $new, is_dir( OMGF_UPLOAD_DIR . "/$old" ), "$old -> $new" );
					$this->assertSame( 'cached', file_get_contents( OMGF_UPLOAD_DIR . '/theme-12/test.css' ) );
				} finally {
					remove_filter( 'omgf_setting_cache_keys', $keys );
					OMGF::reset_cache();
					OMGF::delete( OMGF_UPLOAD_DIR . "/$old" );
					OMGF::delete( OMGF_UPLOAD_DIR . '/theme-12' );
				}
			}
		} finally {
			remove_filter( 'omgf_setting_optimized_fonts_frontend', $fonts );
			OMGF::reset_cache();
		}
	}

}
